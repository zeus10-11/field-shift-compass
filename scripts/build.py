#!/usr/bin/env python3
"""Build script for Vercel deployment.

Precomputes the analytics boot payload at build time (not runtime startup)
and inlines it into static HTML. Copies static assets into public/.
Generates api/_data.py with all precomputed API responses so the serverless
handler can serve them without recomputing or touching disk at runtime.
"""
import json
import os
import pprint
import shutil
import sys

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BACKEND_DIR = os.path.join(PROJECT_ROOT, "backend")
WEB_DIR = os.path.join(PROJECT_ROOT, "web")
PUBLIC_DIR = os.path.join(PROJECT_ROOT, "public")
API_DIR = os.path.join(PROJECT_ROOT, "api")

sys.path.insert(0, BACKEND_DIR)

import config  # noqa: E402
import main  # noqa: E402


def main_build():
    # --- Run the same analytics as main.load_state() ---
    main.load_state()

    boot = main.boot_payload()

    # --- Flatten timeline steps: app.js renderTimeline() reads s.top,
    # s.runner, s.temp_add directly on each step, but boot_payload nests
    # them inside scenarios[]. Pull the medium scenario up to step level.
    for step in boot["timeline"]["steps"]:
        medium = step["scenarios"][1]  # medium scenario
        step["temp_add"] = medium["temp_add"]
        step["top"] = medium["top"]
        step["runner"] = medium["runner"]

    # --- Precompute all API responses ---
    data = {
        "META": boot["meta"],
        "SHIFTS": boot["shifts"],
        "TWIN": boot["twin"],
        "ADVICE": boot["advice"],
        "CLIMATOLOGY": boot["climatology"],
        "CANDIDATES": boot["candidates"],
        "RISK_CALENDAR": boot["risk"],
        "BACKTEST": boot["backtest"],
        "TIMELINE": boot["timeline"],
        # season-plan accepts an optional POST body; precompute the default
        "SEASON_PLAN": main.season_plan(),
        # feedback is read-only on serverless (no writable disk)
        "FEEDBACK": [
            {
                "id": 1,
                "advice_type": "sowing_date",
                "decision": "follow",
                "farmer_note": "Waited 8 days more this year - rain came on time. Will do again next year.",
                "source": "farmer",
                "created_at": "2026-06-12T09:30:00",
            },
            {
                "id": 2,
                "advice_type": "sowing_date",
                "decision": "approved",
                "farmer_note": "Matches district crop-calendar trial results. Approving for WhatsApp broadcast.",
                "source": "agronomist",
                "created_at": "2026-06-13T18:05:00",
            },
        ],
    }

    # --- Write api/_data.py ---
    os.makedirs(API_DIR, exist_ok=True)
    lines = ["# Auto-generated by scripts/build.py — do not edit\n\n"]
    for key, value in data.items():
        lines.append(f"{key} = {pprint.pformat(value, width=100)}\n")
    with open(os.path.join(API_DIR, "_data.py"), "w") as f:
        f.writelines(lines)

    # --- Build public/ ---
    if os.path.exists(PUBLIC_DIR):
        shutil.rmtree(PUBLIC_DIR)
    os.makedirs(PUBLIC_DIR, exist_ok=True)

    # Copy web/ static assets
    shutil.copytree(WEB_DIR, os.path.join(PUBLIC_DIR, "web"))

    # --- index.html: inline window.__BOOT__ ---
    with open(os.path.join(WEB_DIR, "index.html")) as f:
        html = f.read()

    payload = json.dumps(boot).replace("</", "<\\/")
    html = html.replace(
        '<script src="/web/js/app.js"></script>',
        f"<script>window.__BOOT__={payload};</script>\n<script src='/web/js/app.js'></script>",
    )
    with open(os.path.join(PUBLIC_DIR, "index.html"), "w") as f:
        f.write(html)

    # --- agronomist.html: inline window.__AGRO_BOOT__ ---
    with open(os.path.join(WEB_DIR, "agronomist.html")) as f:
        agro_html = f.read()

    agro_payload = json.dumps(
        {
            "meta": {"district": main.STATE["home"]},
            "advice": {"cards": main.STATE["advice"]},
            "feedback": data["FEEDBACK"],
            "backtest": main.STATE["backtest"],
            "risk": {"calendar": main.STATE["risk_calendar"]},
        }
    ).replace("</", "<\\/")
    agro_html = agro_html.replace(
        "<script>",
        f"<script>window.__AGRO_BOOT__={agro_payload};</script>\n<script>",
        1,
    )
    with open(os.path.join(PUBLIC_DIR, "agronomist.html"), "w") as f:
        f.write(agro_html)

    print("Build complete. public/ is ready.")


if __name__ == "__main__":
    main_build()
